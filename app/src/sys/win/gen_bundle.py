#!/usr/bin/env python3
"""Generate the Windows resources embedding the runtime files of scrcpy-gui.

Usage: gen_bundle.py OUTPUT.rc OUTPUT.h BUNDLE_DIR

All the files of BUNDLE_DIR (not recursive) are embedded as RCDATA resources.
The header lists them (resource id, file name, size) and defines a hash of
their content, used to version the extraction directory.
"""

import hashlib
import os
import sys

FIRST_ID = 5000


def main():
    out_rc, out_h, bundle_dir = sys.argv[1:4]
    names = sorted(f for f in os.listdir(bundle_dir)
                   if os.path.isfile(os.path.join(bundle_dir, f)))
    if not names:
        sys.exit('No file to bundle in ' + bundle_dir)

    digest = hashlib.sha256()
    rc = ['// Generated by gen_bundle.py, do not edit', '']
    entries = []
    for i, name in enumerate(names):
        path = os.path.abspath(os.path.join(bundle_dir, name))
        with open(path, 'rb') as f:
            data = f.read()
        digest.update(name.encode() + b'\0' + data)
        res_id = FIRST_ID + i
        rc.append(f'{res_id} RCDATA "{path.replace(os.sep, "/")}"')
        entries.append(f'    {{{res_id}, "{name}", {len(data)}}},')

    h = [
        '// Generated by gen_bundle.py, do not edit',
        '#pragma once',
        '',
        f'#define SC_BUNDLE_HASH "{digest.hexdigest()[:16]}"',
        '',
        'static const struct sc_bundle_file {',
        '    int id;',
        '    const char *name;',
        '    unsigned long long size;',
        '} sc_bundle_files[] = {',
        *entries,
        '};',
        '',
    ]

    with open(out_rc, 'w', newline='\n') as f:
        f.write('\n'.join(rc) + '\n')
    with open(out_h, 'w', newline='\n') as f:
        f.write('\n'.join(h))


if __name__ == '__main__':
    main()
