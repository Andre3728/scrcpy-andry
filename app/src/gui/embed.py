#!/usr/bin/env python3
"""Embed binary files as C arrays.

Usage: embed.py OUTPUT.h NAME=FILE [NAME=FILE ...]

Generates a header with, for each NAME:
    static const unsigned char NAME[] = {...};
    static const unsigned NAME_size = ...;
"""

import sys


def main():
    out_path = sys.argv[1]
    lines = ['// Generated by embed.py, do not edit', '#pragma once', '']
    for arg in sys.argv[2:]:
        name, path = arg.split('=', 1)
        with open(path, 'rb') as f:
            data = f.read()
        lines.append(f'static const unsigned char {name}[] = {{')
        for i in range(0, len(data), 20):
            chunk = data[i:i + 20]
            lines.append('    ' + ','.join(str(b) for b in chunk) + ',')
        lines.append('};')
        lines.append(f'static const unsigned {name}_size = {len(data)};')
        lines.append('')
    with open(out_path, 'w', newline='\n') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
